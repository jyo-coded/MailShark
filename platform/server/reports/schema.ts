// JSON Schema (draft 2020-12) of mailshark.forensic-report/1.0.0. Served at /api/schema/report and
// used by the test-suite to validate every generated report. Additive changes bump the minor
// version; anything that removes or renames a field bumps the major version.
const str = { type: 'string' } as const;
const nstr = { type: ['string', 'null'] } as const;
const num = { type: 'number' } as const;
const nnum = { type: ['number', 'null'] } as const;
const int = { type: 'integer' } as const;
const bool = { type: 'boolean' } as const;
const strArr = { type: 'array', items: str } as const;

const obj = (properties: Record<string, unknown>, required: string[] = Object.keys(properties), extra = false): Record<string, unknown> => ({
  type: 'object',
  properties,
  required,
  additionalProperties: extra,
});

const finding = obj({
  id: str,
  title: str,
  category: str,
  severity: { enum: ['info', 'low', 'medium', 'high', 'critical'] },
  weight: num,
  method: { type: ['string', 'null'], enum: ['protocol', 'heuristic', 'statistical', 'intel', 'correlation', null] },
  detail: str,
  rationale: nstr,
  evidence: { type: 'array', items: obj({ label: str, value: str }) },
  components: strArr,
  limitations: nstr,
  recommendedActions: strArr,
  attack: { type: 'array', items: obj({ id: { type: 'string', pattern: '^T\\d{4}(\\.\\d{3})?$' }, name: str }) },
});

const message = obj({
  id: str,
  evidenceId: str,
  derivation: { enum: ['original', 'extracted-from-mbox', 'extracted-from-emlx', 'reconstructed-from-msg'] },
  containerIndex: int,
  byteOffset: { type: ['integer', 'null'] },
  sha256: { type: 'string', pattern: '^[0-9a-f]{64}$' },
  size: int,
  status: { enum: ['queued', 'running', 'analyzed', 'failed', 'duplicate'] },
  duplicateOf: nstr,
  summary: obj({ subject: nstr, from: nstr, fromName: nstr, to: nstr, date: nstr, messageId: nstr }),
  classification: {
    oneOf: [
      { type: 'null' },
      obj({
        class: { enum: ['benign', 'suspicious', 'malicious', 'inconclusive', 'failed', null] },
        severity: nstr,
        confidence: { enum: ['low', 'medium', 'high', null] },
        riskScore: nnum,
        evidenceCoverage: nnum,
        rationale: strArr,
        thresholds: {},
      }),
    ],
  },
  observations: { type: ['object', 'null'] },
  findings: { type: 'array', items: finding },
  indicators: { type: 'array', items: obj({ type: str, value: str, role: str, component: str, context: nstr, suspicious: bool }) },
  intelligence: {
    type: 'array',
    items: obj({ source: str, indicatorType: str, indicator: str, matchType: str, matchedValue: str, strength: num, firstSeen: nstr, lastSeen: nstr, threat: nstr, family: nstr, reference: nstr, suppressed: nstr }),
  },
  campaign: { oneOf: [{ type: 'null' }, obj({ clusterId: str, label: str })] },
  processing: obj({
    analyzedAt: nstr,
    engineVersion: nstr,
    configHash: nstr,
    intelSnapshot: nstr,
    durationMs: nnum,
    resultSha256: nstr,
    attempts: int,
    history: { type: 'array', items: obj({ at: str, event: str, detail: {} }) },
  }),
  error: { oneOf: [{ type: 'null' }, obj({ code: str, detail: nstr })] },
});

